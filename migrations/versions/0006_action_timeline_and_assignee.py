def _backfill_from_audit_log() -> None:
    """Give existing actions a history: who created them and when, and which fields later
    changes touched (the audit log kept the field names, not the old and new values)."""
    import json

    bind = op.get_bind()
    existing = {row[0] for row in bind.execute(sa.text("SELECT id FROM action"))}
    rows = bind.execute(sa.text(
        "SELECT event, resource_id, actor_user_id, actor_username, details, created_at "
        "FROM audit_log WHERE event IN ('action.created', 'action.updated') ORDER BY id"
    )).all()
    events = []
    for event, resource_id, user_id, username, details, created_at in rows:
        try:
            action_id = int(resource_id)
        except (TypeError, ValueError):
            continue
        if action_id not in existing:
            continue  # deleted since
        if event == "action.created":
            events.append({"action_id": action_id, "kind": "creation", "changes": None,
                           "author_user_id": user_id, "author_username": username, "created_at": created_at})
            continue
        fields = (json.loads(details) if details else {}).get("updated_fields", [])
        if not fields:
            continue
        changes = [{"champ": f, "avant": None, "apres": None} for f in fields]  # values not kept
        events.append({"action_id": action_id, "kind": "modification",
                       "changes": json.dumps(changes, ensure_ascii=False),
                       "author_user_id": user_id, "author_username": username, "created_at": created_at})
    if events:
        bind.execute(sa.text(
            "INSERT INTO action_event (action_id, kind, changes, author_user_id, author_username, created_at) "
            "VALUES (:action_id, :kind, :changes, :author_user_id, :author_username, :created_at)"
        ), events)


